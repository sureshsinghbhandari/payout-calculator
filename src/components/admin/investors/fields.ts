/**
 * Pure helpers for the investors admin area: form field validation (used by
 * the server actions; nothing from the browser is trusted), the username
 * suggestion for converted inquiries, and display helpers.
 */
import { normalizeUsername, setupState, validatePersonName, validateUsername, type Investor } from "@/lib/accounts";
import { INVESTMENT_AMOUNTS, LOCK_IN_YEARS } from "@/lib/config";
import {
  FREQUENCY_LABELS,
  PAYOUT_TYPE_LABELS,
  validateInvestmentDate,
  type PayoutFrequency,
  type PayoutType,
} from "@/lib/payout";

export const CONTACT_FIELDS = ["name", "email", "phone", "username"] as const;
export const PLAN_FIELDS = ["principal", "investmentDate", "lockInYears", "frequency", "payoutType"] as const;
export const CONVERT_FIELDS = [...CONTACT_FIELDS, ...PLAN_FIELDS] as const;

export type ContactField = (typeof CONTACT_FIELDS)[number];
export type PlanField = (typeof PLAN_FIELDS)[number];
export type ConvertField = ContactField | PlanField;

export type FieldErrors<F extends string> = Partial<Record<F, string>>;

const EMAIL_MAX = 254;
const PHONE_MAX = 25;
const EMAIL_PATTERN = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/;
const PHONE_PATTERN = /^[+()\-.\s\d]+$/;
// Control characters are never valid in these single-line fields.
const CONTROL_CHARS = /[\u0000-\u001F\u007F]/;
/** Longest value echoed back into a form after an error. */
const ECHO_MAX = 300;

function text(value: unknown): string {
  return typeof value === "string" ? value.trim() : "";
}

/** The submitted value of each field as a string (to show the form again after an error). */
export function readFields<F extends string>(formData: FormData, fields: readonly F[]): Record<F, string> {
  const values = {} as Record<F, string>;
  for (const name of fields) {
    const value = formData.get(name);
    values[name] = typeof value === "string" ? value.slice(0, ECHO_MAX) : "";
  }
  return values;
}

/** Investor ids are generated by the store ("inv_" + hex); accept only id-like strings. */
export function isInvestorIdLike(id: unknown): id is string {
  return typeof id === "string" && /^[A-Za-z0-9_-]{1,64}$/.test(id);
}

export interface ContactValues {
  name: string;
  email: string;
  phone: string;
  username: string;
}

export function parseContactFields(
  raw: Partial<Record<ContactField, unknown>>,
): { ok: true; value: ContactValues } | { ok: false; errors: FieldErrors<ContactField> } {
  const errors: FieldErrors<ContactField> = {};
  const name = text(raw.name).replace(/\s+/g, " ");
  const email = text(raw.email).toLowerCase();
  const phone = text(raw.phone);
  const username = normalizeUsername(text(raw.username));

  const nameError = validatePersonName(name);
  if (nameError) errors.name = nameError;
  else if (CONTROL_CHARS.test(name)) errors.name = "Enter a valid name.";

  if (email === "") errors.email = "Enter an email address.";
  else if (email.length > EMAIL_MAX || !EMAIL_PATTERN.test(email) || CONTROL_CHARS.test(email)) {
    errors.email = "Enter a valid email address, like name@example.com.";
  }

  if (phone !== "") {
    const digits = phone.replace(/\D/g, "").length;
    if (phone.length > PHONE_MAX || !PHONE_PATTERN.test(phone) || digits < 7 || digits > 15) {
      errors.phone = "Enter a valid phone number, or leave it empty.";
    }
  }

  const usernameError = validateUsername(username);
  if (usernameError) errors.username = usernameError;

  if (Object.keys(errors).length > 0) return { ok: false, errors };
  return { ok: true, value: { name, email, phone, username } };
}

export interface PlanValues {
  principal: number;
  investmentDate: string;
  lockInYears: number;
  frequency: PayoutFrequency;
  payoutType: PayoutType;
}

export function parsePlanFields(
  raw: Partial<Record<PlanField, unknown>>,
): { ok: true; value: PlanValues } | { ok: false; errors: FieldErrors<PlanField> } {
  const errors: FieldErrors<PlanField> = {};

  const principalText = text(raw.principal);
  const principal = /^\d+$/.test(principalText) ? Number(principalText) : NaN;
  if (!(INVESTMENT_AMOUNTS as readonly number[]).includes(principal)) {
    errors.principal = "Choose one of the listed investment amounts.";
  }

  const date = validateInvestmentDate(text(raw.investmentDate));
  if (!date.ok) errors.investmentDate = date.error;

  const yearsText = text(raw.lockInYears);
  const lockInYears = /^\d+$/.test(yearsText) ? Number(yearsText) : NaN;
  if (!(LOCK_IN_YEARS as readonly number[]).includes(lockInYears)) {
    errors.lockInYears = "Choose one of the listed terms.";
  }

  const frequency = text(raw.frequency);
  if (!Object.hasOwn(FREQUENCY_LABELS, frequency)) errors.frequency = "Choose a payout term.";

  const payoutType = text(raw.payoutType);
  if (!Object.hasOwn(PAYOUT_TYPE_LABELS, payoutType)) errors.payoutType = "Choose a payout type.";

  if (Object.keys(errors).length > 0 || !date.ok) return { ok: false, errors };
  return {
    ok: true,
    value: {
      principal,
      investmentDate: date.value,
      lockInYears,
      frequency: frequency as PayoutFrequency,
      payoutType: payoutType as PayoutType,
    },
  };
}

function usernameSlug(raw: string): string {
  return normalizeUsername(raw)
    .replace(/[^a-z0-9._-]/g, "")
    .replace(/^[^a-z0-9]+/, "")
    .slice(0, 32)
    .replace(/[._-]+$/, "");
}

/**
 * A valid, unused username suggestion: from the email's local part (invalid
 * characters removed), else from the name, else "investor". A number is
 * appended when the username is already taken.
 */
export function suggestUsername(email: string, name: string, taken: ReadonlySet<string>): string {
  const local = email.split("@")[0] ?? "";
  const candidates = [usernameSlug(local), usernameSlug(name.trim().replace(/\s+/g, "."))];
  const base = candidates.find((c) => validateUsername(c) === null) ?? "investor";
  if (!taken.has(base)) return base;
  for (let n = 2; n < 10_000; n++) {
    const suffix = String(n);
    const candidate = `${base.slice(0, 32 - suffix.length).replace(/[._-]+$/, "")}${suffix}`;
    if (validateUsername(candidate) === null && !taken.has(candidate)) return candidate;
  }
  return base;
}

export type LoginStateKey = "disabled" | "must-change" | "has-password" | "link-pending" | "not-set-up";

export interface LoginState {
  key: LoginStateKey;
  label: string;
  /** Extra detail, e.g. until when a setup link is valid. */
  detail?: string;
}

/** Sign-in state of an investor for display. Server components only (takes the full record). */
export function investorLoginState(investor: Investor, nowMs: number): LoginState {
  if (!investor.active) return { key: "disabled", label: "Login disabled" };
  const state = setupState(investor, nowMs);
  const linkPending =
    investor.setupTokenHash !== null &&
    investor.setupExpiresAt !== null &&
    Date.parse(investor.setupExpiresAt) > nowMs;
  const linkDetail =
    linkPending && investor.setupExpiresAt
      ? `Setup link valid until ${formatTimestamp(investor.setupExpiresAt)}`
      : undefined;
  if (state === "active") {
    return investor.mustChangePassword
      ? { key: "must-change", label: "Must change password", detail: linkDetail }
      : { key: "has-password", label: "Has password", detail: linkDetail };
  }
  if (state === "link-pending") return { key: "link-pending", label: "Setup link pending", detail: linkDetail };
  if (state === "link-expired") return { key: "not-set-up", label: "Not set up", detail: "Setup link expired" };
  return { key: "not-set-up", label: "Not set up" };
}

