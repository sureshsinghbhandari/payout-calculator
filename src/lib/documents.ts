/**
 * Investor documents (agreements, certificates, tax documents...): shared
 * types and pure helpers. Master Admins upload them on the investor's page;
 * investors download their own in the portal.
 */

export type DocumentType = "agreement" | "certificate" | "tax" | "statement" | "other";

export const DOCUMENT_TYPE_LABELS: Record<DocumentType, string> = {
  agreement: "Agreement",
  certificate: "Certificate",
  tax: "Tax document",
  statement: "Statement",
  other: "Other",
};

export type DocumentKind = "pdf" | "jpeg" | "png";

/** Accepted file kinds: extension, content type and label. */
export const DOCUMENT_KINDS: Record<DocumentKind, { extension: string; contentType: string; label: string }> = {
  pdf: { extension: "pdf", contentType: "application/pdf", label: "PDF" },
  jpeg: { extension: "jpg", contentType: "image/jpeg", label: "JPEG" },
  png: { extension: "png", contentType: "image/png", label: "PNG" },
};

export const MAX_DOCUMENT_BYTES = 10 * 1024 * 1024;
export const DOCUMENT_TITLE_MAX = 100;
const FILE_NAME_MAX = 120;

export interface InvestorDocument {
  id: string;
  investorId: string;
  title: string;
  type: DocumentType;
  kind: DocumentKind;
  /** File name for downloads (the uploaded file's name, cleaned up). */
  fileName: string;
  /** Private blob pathname. Never sent to the browser. */
  pathname: string;
  size: number;
  uploadedAt: string;
  /** Name and id of the admin who uploaded it. */
  uploadedBy: string;
  uploadedById: string;
}

/** What the browser may see of a document (no blob pathname). */
export interface PublicDocument {
  id: string;
  title: string;
  type: DocumentType;
  kind: DocumentKind;
  fileName: string;
  size: number;
  uploadedAt: string;
  uploadedBy: string;
}

export function toPublicDocument(doc: InvestorDocument): PublicDocument {
  return {
    id: doc.id,
    title: doc.title,
    type: doc.type,
    kind: doc.kind,
    fileName: doc.fileName,
    size: doc.size,
    uploadedAt: doc.uploadedAt,
    uploadedBy: doc.uploadedBy,
  };
}

export function isDocumentType(value: unknown): value is DocumentType {
  return typeof value === "string" && Object.hasOwn(DOCUMENT_TYPE_LABELS, value);
}

/** Document ids are generated by the store ("doc_" + hex). */
export function isDocumentId(value: unknown): value is string {
  return typeof value === "string" && /^doc_[a-f0-9]{12}$/.test(value);
}

/** The file kind from the file's first bytes (its "magic number"), or null when it is not a PDF, JPEG or PNG. */
export function detectDocumentKind(bytes: Uint8Array): DocumentKind | null {
  const starts = (sig: number[]) => sig.every((b, i) => bytes[i] === b);
  if (starts([0x25, 0x50, 0x44, 0x46, 0x2d])) return "pdf"; // %PDF-
  if (starts([0xff, 0xd8, 0xff])) return "jpeg";
  if (starts([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a])) return "png";
  return null;
}

/** The kind a file name's extension claims, or null. */
export function kindFromFileName(name: string): DocumentKind | null {
  const ext = name.toLowerCase().split(".").pop() ?? "";
  if (ext === "pdf") return "pdf";
  if (ext === "jpg" || ext === "jpeg") return "jpeg";
  if (ext === "png") return "png";
  return null;
}

// Control characters and characters that are unsafe in file names.
const UNSAFE_NAME_CHARS = /[\u0000-\u001F\u007F"\\/:*?<>|]+/g;

/** A safe download file name with the extension of the detected kind. */
export function cleanFileName(raw: string, kind: DocumentKind, fallback: string): string {
  const base = raw
    .replace(UNSAFE_NAME_CHARS, " ")
    .replace(/\.[A-Za-z0-9]{1,5}$/, "")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, FILE_NAME_MAX);
  return `${base || fallback}.${DOCUMENT_KINDS[kind].extension}`;
}

export function parseDocumentTitle(raw: unknown): { ok: true; value: string } | { ok: false; error: string } {
  const title = (typeof raw === "string" ? raw : "").replace(/\s+/g, " ").trim();
  if (title === "") return { ok: false, error: "Enter a title." };
  if (title.length > DOCUMENT_TITLE_MAX) return { ok: false, error: `Use at most ${DOCUMENT_TITLE_MAX} characters.` };
  if (/[\u0000-\u001F\u007F]/.test(title)) return { ok: false, error: "Enter a valid title." };
  return { ok: true, value: title };
}

/** "2.4 MB", "830 KB" */
export function formatFileSize(bytes: number): string {
  if (bytes >= 1024 * 1024) return `${(bytes / (1024 * 1024)).toFixed(1)} MB`;
  return `${Math.max(1, Math.round(bytes / 1024))} KB`;
}

/** Newest first. */
export function sortDocuments<T extends Pick<InvestorDocument, "uploadedAt">>(docs: readonly T[]): T[] {
  return [...docs].sort((a, b) => (a.uploadedAt < b.uploadedAt ? 1 : a.uploadedAt > b.uploadedAt ? -1 : 0));
}
